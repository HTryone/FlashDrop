export type BlockType = 'p' | 'ul' | 'ol' | 'callout' | 'table' | 'code';
export type CalloutVariant = 'tip' | 'warn' | 'secure' | 'note';

export interface Block {
  type: BlockType;
  text?: string; // p / callout / code 用
  items?: string[]; // ul / ol 用
  variant?: CalloutVariant; // callout 用
  headers?: string[]; // table 用
  rows?: string[][]; // table 用
}

export interface Section {
  id: string;
  title: string;
  blocks: Block[];
}

// 把 **加粗** 与 `代码` 转成安全 HTML（内容为本文件静态作者文案，无外部输入，v-html 安全）。
export function formatInline(src: string): string {
  const esc = src
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;');
  return esc
    .replace(/\*\*(.+?)\*\*/g, '<strong>$1</strong>')
    .replace(/`(.+?)`/g, '<code>$1</code>');
}

